CREATE TABLE execution_step_checkpoints (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    execution_id BIGINT NOT NULL
        REFERENCES workflow_executions(id),

    workflow_step_id BIGINT NOT NULL
        REFERENCES workflow_steps(id),

    status VARCHAR(30) NOT NULL,

    attempt_token VARCHAR(64) NOT NULL,

    attempt_number INTEGER NOT NULL,

    lease_until TIMESTAMPTZ,

    failure_reason VARCHAR(1000),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_execution_step_checkpoint
        UNIQUE (execution_id, workflow_step_id),

    CONSTRAINT chk_execution_step_checkpoint_status
        CHECK (status IN ('RUNNING', 'SUCCEEDED', 'FAILED')),

    CONSTRAINT chk_execution_step_attempt_number
        CHECK (attempt_number > 0)
);

-- One in-progress step per execution. A second consumer cannot
-- insert another active claim for the same execution.
CREATE UNIQUE INDEX uq_execution_step_active_attempt
ON execution_step_checkpoints (execution_id)
WHERE status = 'RUNNING';
