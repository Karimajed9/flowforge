ALTER TABLE workflows
ADD CONSTRAINT uq_workflows_webhook_token_hash
UNIQUE (webhook_token_hash);

CREATE TABLE workflow_executions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    workflow_id BIGINT NOT NULL
        REFERENCES workflows(id) ON DELETE RESTRICT,

    status VARCHAR(30) NOT NULL,

    payload JSONB NOT NULL,

    created_at TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_execution_status
        CHECK (status IN (
            'RECEIVED',
            'QUEUED',
            'RUNNING',
            'SUCCEEDED',
            'FAILED'
        ))
);

CREATE INDEX idx_workflow_executions_workflow
ON workflow_executions(workflow_id, created_at DESC);
